import { randomInt } from 'node:crypto';

/** mulberry32: tiny, fast, good-enough PRNG for scheduling decisions. Not for cryptography. */
export function mulberry32(seed: number): () => number {
  let a = seed >>> 0;
  return () => {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

export class Rng {
  private readonly next: () => number;
  constructor(seed: number) {
    this.next = mulberry32(seed);
  }
  /** [0, 1) */
  float(): number {
    return this.next();
  }
  /** Integer in [min, max], inclusive. */
  int(min: number, max: number): number {
    if (max < min) return min;
    return min + Math.floor(this.next() * (max - min + 1));
  }
  chance(p: number): boolean {
    return p > 0 && this.next() < p;
  }
}

/** 32-bit FNV-1a hash. Used to derive stable per-call decisions from a seed. */
export function hashString(input: string): number {
  let h = 0x811c9dc5;
  for (let i = 0; i < input.length; i++) {
    h ^= input.charCodeAt(i);
    h = Math.imul(h, 0x01000193);
  }
  return h >>> 0;
}

export function randomSeed(): number {
  return randomInt(1, 2 ** 31 - 1);
}
